"""Experiment 30: internal robustness benchmark -- how much of this pipeline is REAL?

Three questions, each measured rather than asserted:

  A. GENERALISATION.  Does the score survive on sessions we have never seen?
     `materialize_hidden_fields()` derives the intent card and the behaviour from the
     TARGET PRODUCT ALONE -- a stored sample carries only {sample_id, scenario_type,
     user_profile, ground_truth}. So a minted session is not an approximation of a
     private one: it is generated by the identical code path over the identical frozen
     catalogue. Minting 800 sessions from products that appear in NO public session, at
     the organizer's own 40/40/15/5 mix, is the closest thing to the private set that
     exists outside the organizer's machine.

     Three target distributions are used, because the target distribution is the one
     population property our ranker leans on (W_POP):
       reviews   P(target) ~ rating_number, with replacement -- matches the real split
                 (verified in pass 21: real median 8.80 vs minted 8.84)
       uniform   every product equally likely -- a population where popularity is
                 uninformative
       inverse   P(target) ~ 1/(1+rating_number) -- a population where popularity is
                 ANTI-correlated with the answer. Deliberately adversarial.

  B. POPULATION VARIANCE.  Bootstrap over sessions gives a 95% interval for the score,
     so "is this difference real" stops being a judgement call.

  C. COMPONENT ATTRIBUTION.  Leave-one-component-out, scored on the UNSEEN 800 rather
     than on the sessions the components were tuned against. A component that only pays
     out on the public 200 is a component that memorised the public 200.

  D. HYPERPARAMETER SENSITIVITY.  For each tuned constant, the score spread across a
     plausible range, again on unseen sessions. A flat response means the constant is
     not carrying population-specific information.

Run:  PYTHONIOENCODING=utf-8 python -u experiments/log/30_robustness_benchmark.py
"""
from __future__ import annotations

import json
import random
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from evaluator.local_evaluator import catalog_index, evaluate, load_jsonl  # noqa: E402
from submission.agent import CAT, CONSTRAINT, MINED, Agent  # noqa: E402

SEEDS = {"reviews": 1001, "uniform": 1002, "inverse": 1003}  # literal: hash() is per-process randomised
MIX = [("buying", 0.40), ("browsing", 0.40), ("intent_override", 0.15), ("boundary", 0.05)]
N_SYNTH = 800


def mint(prods, exclude, profiles, weighting: str, n: int, seed: int) -> list[dict]:
    """Build `n` sessions in public_set.jsonl shape, targets drawn under `weighting`."""
    rng = random.Random(seed)
    cand = [a for a in prods if a not in exclude]

    def rn(a):
        try:
            return float(prods[a].get("rating_number") or 0)
        except (TypeError, ValueError):
            return 0.0

    if weighting == "reviews":
        w = [rn(a) for a in cand]
    elif weighting == "uniform":
        w = [1.0] * len(cand)
    elif weighting == "inverse":
        w = [1.0 / (1.0 + rn(a)) for a in cand]
    else:
        raise ValueError(weighting)

    targets = rng.choices(cand, weights=w, k=n)
    scen = []
    for name, frac in MIX:
        scen += [name] * int(round(frac * n))
    while len(scen) < n:
        scen.append("browsing")
    scen = scen[:n]
    rng.shuffle(scen)
    return [{"sample_id": f"synth_{weighting}_{i:04d}", "scenario_type": scen[i],
             "user_profile": profiles[i % len(profiles)],
             "ground_truth": {"parent_asin": targets[i]}} for i in range(n)]


def main() -> None:
    t_start = time.time()
    samples = load_jsonl(ROOT / "data" / "public_set.jsonl")
    cid, cats, prods = catalog_index(ROOT / "data" / "catalog.jsonl")
    base = Agent(ROOT / "data" / "catalog.jsonl")
    public_targets = {str(s["ground_truth"]["parent_asin"]) for s in samples}
    profiles = [s["user_profile"] for s in samples]

    def share(cls=Agent, **kw):
        o = object.__new__(cls)
        o.ix, o.sessions, o.llm = base.ix, {}, None
        for k, v in kw.items():
            setattr(o, k, v)
        return o

    def run(ag, sub, keep=False):
        r = evaluate(ag, sub, cid, cats, prods)
        out = {"score": r["recommended_technical_score"], "hr": r["hit_rate_at_10"],
               "mrr": r["mrr"], "mttc": r["mttc"]}
        if keep:
            out["sessions"] = r["sessions"]
            out["scenario"] = r["scenario_metrics"]
        return out

    SETS = {"public200": samples}
    for wname in ("reviews", "uniform", "inverse"):
        SETS[f"synth800_{wname}"] = mint(prods, public_targets, profiles, wname,
                                         N_SYNTH, seed=SEEDS[wname])
    print(f"minted {N_SYNTH} sessions x 3 target distributions "
          f"(0 overlap with the public 200)   [{time.time()-t_start:.0f}s]\n")

    OUT: dict = {}

    # ---------------------------------------------------------------- A. generalisation
    print("=" * 78)
    print("A. GENERALISATION -- shipped agent on sessions it has never seen")
    print("=" * 78)
    print(f"{'evaluation set':<24}{'score':>9}{'HR':>8}{'MRR':>9}{'MTTC':>8}   n")
    print("-" * 62)
    A = {}
    for name, sub in SETS.items():
        r = run(share(), sub, keep=True)
        A[name] = r
        print(f"{name:<24}{r['score']:>9.5f}{r['hr']:>8.1%}{r['mrr']:>9.4f}"
              f"{r['mttc']:>8.3f}   {len(sub)}")
    OUT["A_generalisation"] = {k: {x: v[x] for x in ("score", "hr", "mrr", "mttc")}
                               for k, v in A.items()}
    print("\n  per-scenario on the unseen review-weighted 800:")
    for k, v in sorted(A["synth800_reviews"]["scenario"].items()):
        print(f"    {k:<18} n={v['sample_count']:>3}  HR {v['hit_rate_at_10']:.1%}  "
              f"MRR {v['mrr']:.4f}  MTTC {v['mttc']:.2f}")
    OUT["A_scenario"] = A["synth800_reviews"]["scenario"]

    # --------------------------------------------------------------- B. sampling variance
    print("\n" + "=" * 78)
    print("B. POPULATION VARIANCE -- bootstrap over sessions (2,000 resamples)")
    print("=" * 78)

    def boot(sessions, reps=2000, seed=0):
        rng = random.Random(seed)
        n = len(sessions)
        vals = []
        for _ in range(reps):
            pick = [sessions[rng.randrange(n)] for _ in range(n)]
            hr = sum(int(s["hit"]) for s in pick) / n
            mrr = statistics.fmean(s["reciprocal_rank"] for s in pick)
            mttc = statistics.fmean(
                s["first_hit_turn"] if s["first_hit_turn"] is not None else 11 for s in pick)
            eff = max(0.0, min(1.0, (11.0 - mttc) / 10.0))
            vals.append(0.5 * hr + 0.3 * mrr + 0.2 * eff)
        vals.sort()
        return {"mean": statistics.fmean(vals), "sd": statistics.pstdev(vals),
                "lo95": vals[int(0.025 * reps)], "hi95": vals[int(0.975 * reps)]}

    B = {}
    for name in ("public200", "synth800_reviews"):
        b = boot(A[name]["sessions"])
        B[name] = b
        print(f"  {name:<20} {A[name]['score']:.5f}   95% CI "
              f"[{b['lo95']:.5f}, {b['hi95']:.5f}]   sd {b['sd']:.5f}")
    OUT["B_bootstrap"] = B
    half = (B["public200"]["hi95"] - B["public200"]["lo95"]) / 2
    print(f"\n  -> on 200 sessions the 95% interval is +/-{half:.4f}. Any measured delta")
    print(f"     smaller than that is not distinguishable from which sessions were drawn.")

    # ------------------------------------------------------------- C. component ablation
    print("\n" + "=" * 78)
    print("C. COMPONENT ATTRIBUTION -- leave-one-out, scored on the UNSEEN 800")
    print("=" * 78)

    class NoLedger(Agent):
        """Forget everything before the current turn."""
        def _observe(self, st, msg):
            st.evidence.clear()
            return super()._observe(st, msg)

    class NoMining(Agent):
        def _observe(self, st, msg):
            saved, self.ix.mine = self.ix.mine, lambda *a, **k: []
            try:
                return super()._observe(st, msg)
            finally:
                self.ix.mine = saved

    class NoTemplates(Agent):
        """Templates off: every message goes through catalogue-grounded mining only."""
        def _extract_templated(self, msg):
            return []

    class NoResolve(Agent):
        """Use the raw constraint text; never back off to an attested substring."""
        def _resolve(self, text, cap=12):
            from submission.agent import raw_toks
            t = raw_toks(text)[:cap]
            return [" ".join(t)] if t else []

    class NoRejection(Agent):
        def respond(self, sid, msg, turn, top_k):
            r = super().respond(sid, msg, turn, top_k)
            st = self.sessions.get(sid)
            if st is not None:
                st.rejected.clear()
            return r

    class NoLadder(Agent):
        """Disjunction only -- drop the conjunctive rungs and the graceful backoff."""
        def _candidates(self, st, message):
            ev = sorted(st.evidence.items(), key=lambda kv: kv[1][0])
            if not ev:
                return super()._candidates(st, message)
            pool = self.ix.search(" OR ".join(f'"{p}"' for p, _ in ev[:14]), self.POOL)
            return pool or super()._candidates(st, message)

    class NoCatSplit(Agent):
        """Revert the pass-29 category fix: adjacency required again."""
        def _extract_templated(self, msg):
            seen, out = set(), []
            for text, tier in super()._extract_templated(msg):
                if tier == CAT and len(text.split()) < 2:
                    continue
                if (text, tier) not in seen:
                    seen.add((text, tier))
                    out.append((text, tier))
            return out

    ABLATIONS = {
        "shipped":                     (Agent, {}),
        "-- session ledger":           (NoLedger, {}),
        "-- n-gram mining":            (NoMining, {}),
        "-- message templates":        (NoTemplates, {}),
        "-- resolve backoff":          (NoResolve, {}),
        "-- rejection feedback":       (NoRejection, {}),
        "-- retrieval ladder":         (NoLadder, {}),
        "-- category part-split":      (NoCatSplit, {}),
        "-- popularity prior":         (Agent, {"W_POP": 0.0}),
        "-- idf weighting":            (Agent, {"IDF_POW": 0.0}),
        "-- tier weights (all equal)": (Agent, {"W_CATEGORY": 1.0, "W_MINED": 1.0}),
        "-- dead-attr skip":           (Agent, {}),          # handled below
        "-- sequential disclosure":    (Agent, {"DISCLOSURE": (10,) * 10}),
    }
    print(f"{'ablation':<30}{'pub200':>9}{'d':>9}{'unseen800':>11}{'d':>9}{'HR800':>8}")
    print("-" * 76)
    C = {}
    ref_p = ref_s = None
    for name, (cls, kw) in ABLATIONS.items():
        if name == "-- dead-attr skip":
            import submission.agent as sa
            saved = sa.DEAD_ATTRIBUTES
            sa.DEAD_ATTRIBUTES = ()
            p = run(share(cls, **kw), SETS["public200"])
            s = run(share(cls, **kw), SETS["synth800_reviews"])
            sa.DEAD_ATTRIBUTES = saved
        else:
            p = run(share(cls, **kw), SETS["public200"])
            s = run(share(cls, **kw), SETS["synth800_reviews"])
        if ref_p is None:
            ref_p, ref_s = p["score"], s["score"]
        C[name] = {"public200": p, "synth800": s,
                   "d_public": p["score"] - ref_p, "d_synth": s["score"] - ref_s}
        print(f"{name:<30}{p['score']:>9.5f}{p['score']-ref_p:>+9.5f}"
              f"{s['score']:>11.5f}{s['score']-ref_s:>+9.5f}{s['hr']:>8.1%}")
    OUT["C_ablation"] = {k: {"d_public": v["d_public"], "d_synth": v["d_synth"],
                             "public": v["public200"], "synth": v["synth800"]}
                         for k, v in C.items()}

    # ------------------------------------------------------ D. hyperparameter sensitivity
    print("\n" + "=" * 78)
    print("D. HYPERPARAMETER SENSITIVITY -- score spread on the UNSEEN 800")
    print("=" * 78)
    SWEEPS = {
        "W_POP":      [0.0, 0.15, 0.25, 0.35, 0.50, 0.75],
        "W_CATEGORY": [0.25, 0.50, 0.75, 1.00],
        "W_MINED":    [0.05, 0.15, 0.30, 0.60],
        "IDF_POW":    [0.0, 0.2, 0.35, 0.5, 0.8],
        "POOL":       [150, 250, 400, 700],
        "STRONG_DF":  [150, 300, 500, 1000],
    }
    D = {}
    sub = SETS["synth800_reviews"]
    for pname, vals in SWEEPS.items():
        scores = []
        for v in vals:
            scores.append(run(share(**{pname: v}), sub)["score"])
        spread = max(scores) - min(scores)
        best = vals[scores.index(max(scores))]
        shipped_v = getattr(Agent, pname)
        D[pname] = {"values": vals, "scores": scores, "spread": spread,
                    "argmax_unseen": best, "shipped": shipped_v}
        flag = "FLAT" if spread < 0.010 else "sensitive"
        print(f"  {pname:<12} spread {spread:.5f}  {flag:<10} "
              f"shipped={shipped_v}  argmax(unseen)={best}")
        print(f"               " + "  ".join(f"{v}:{s:.4f}" for v, s in zip(vals, scores)))
    OUT["D_sensitivity"] = D

    (ROOT / "experiments" / "results" / "out_30.json").write_text(
        json.dumps(OUT, indent=2, default=str) + "\n", encoding="utf-8")
    print(f"\n[saved] experiments/results/out_30.json   total {time.time()-t_start:.0f}s")


if __name__ == "__main__":
    main()
